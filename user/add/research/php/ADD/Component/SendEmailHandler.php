class ADD_Component_SendEmailHandler extends ADD_Component_Encounter_Modal
{
    function submit($values)
    {
        $cuInterpolate = $i = new \ClinicLE\System\Service\Interpolate();
        $emailMsg = $values['email'];
        $emailMsg = $cuInterpolate->render($emailMsg,array("first_name"=>"DICTATE","last_name"=>"EDITESTPATIENT","id"=>"ILH1234567"));
        $emailAddr = "robert.free@uhl-tr.nhs.uk";
        $sent = mail($emailAddr, "Respiratory research database", $emailMsg, "From: Leicester BRC - Respiratory <noreply@uhl-tr.nhs.uk>");
        if(!$sent) {
            CLE::web()->addError("Unable to send email");
            return;
        }
        $values['change_comments']="Email sent to patient directly";
        unset($values['email']);
        $values['contact_method']=array("4"=>"4");
        return parent::submit($values); // TODO: Change the autogenerated stub
    }
}