namespace ClinicLE\Command;

use ClinicLE\System\Environment\AbstractEnvironment;
use ClinicLE\System\System;
use Symfony\Component\Console\Application;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;

class CommandApplication extends Application
{
    private $commandRunner;
    private $modules; /** @var  ModuleCollection */
    private $events; /** @var  EventDispatcher */
    private $systemConfig; /** @var AbstractConfig */
    private $services; /** @var Services */
    private $env; /** @var AbstractEnvironment */

    /**
     * @return Services
     */
    public function getEnv()
    {
        return $this->env;
    }

    /**
     * @param Services $env
     */
    public function setEnv($env)
    {
        $this->env = $env;
    } /** @var AbstractEnvironment */
    /**
     * @return mixed
     */
    public function getModules()
    {
        return $this->modules;
    }

    /**
     * @param mixed $modules
     */
    public function setModules($modules)
    {
        $this->modules = $modules;
    }

    /**
     * @return ModuleCollection
     */
    public function getEvents()
    {
        return $this->events;
    }

    /**
     * @param ModuleCollection $events
     */
    public function setEvents($events)
    {
        $this->events = $events;
    }

    /**
     * @return EventDispatcher
     */
    public function getSystemConfig()
    {
        return $this->systemConfig;
    }

    /**
     * @param EventDispatcher $systemConfig
     */
    public function setSystemConfig($systemConfig)
    {
        $this->systemConfig = $systemConfig;
    }

    /**
     * @return mixed
     */
    public function getServices()
    {
        return $this->services;
    }

    /**
     * @param mixed $services
     */
    public function setServices($services)
    {
        $this->services = $services;
    }

    function __construct($name, $version, System $system) {
        $this->modules = $system->getModules();
        $this->events = $system->getEvents();
        $this->systemConfig = $system->getConfig();
        $this->services = $system->getServiceContainer();
        $this->env = $system->getEnvironment();
        parent::__construct($name, $version);
    }

    /**
     * @return CommandRunner
     */
    public function getCommandRunner()
    {
        return $this->commandRunner;
    }

    /**
     * @param mixed $commandRunner
     */
    public function setCommandRunner($commandRunner)
    {
        $this->commandRunner = $commandRunner;
    }

    protected function doRunCommand(Command $command, InputInterface $input, OutputInterface $output)
    {
        $log = \CLE::log($this);

        $log->running();
        $exit_code = parent::doRunCommand($command, $input, $output); // TODO: Change the autogenerated stub
        $log->complete();
        return $exit_code;
    }
}