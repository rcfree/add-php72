namespace ClinicLE\Search\Field;


class EmailResultsButtonField extends \ADD_Field_Button
{
    function getOnClick($page)
    {
        return "var sg = CLE.Client.element('".$this->getSetting("search_results_grid")."'); if(sg) {sg.scope().emailResults(); }";
    }
    function getLinkTitle($page)
    {
        return "<i class='icon-leaf'></i>&nbsp;" . $this->getTitle();
    }
    function getFieldHtmlAttrs($page)
    {
        $attrs = parent::getFieldHtmlAttrs($page); // TODO: Change the autogenerated stub
        $attrs['cle-nong']=1;
        return $attrs;
    }
}