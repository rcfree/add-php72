namespace COPD\Main\Field;

use CLE;
use ClinicLE\Data\RecordManager;

/**
 * Description of AddContactButtonField
 *
 * @author rcf8
 */
abstract class ConvertToReferralButtonField extends \ADD_Field_Submit {
    protected $referralIdField = null;
    protected $targetIdField = null;

    const COMORB_ENC_TYPE = "copd-comorb-record";

    const DRUG_ENC_TYPE = "copd-drug-record";

    function finaliseField($page)
    {
        if (CLE::sys()->config("disable_copd_pr_link")) {
            return null;
        }

        parent::finaliseField($page); // TODO: Change the autogenerated stub
        $this->setSetting("parent_key","buttons");
        $this->referralIdField = $this->assertSetting("referral_id_field");
        $this->targetIdField = $this->assertSetting("target_id_field");

    }

    function afterPopulateFields($page)
    {
        $data = $page->getData();
        if(!empty($data[$this->referralIdField])) {
            $this->setHidden(true,$page);
        }

    }

    function getLinkTitle($page) {
        return "<i class='fa fa-exchange'></i>&nbsp;Convert to ".$this->getTitle();
    }

    function beforeSubmitValues(&$values, $page)
    {
        if(!isset($values[$this->getName()])) {
            return;
        }
        if(!empty($values[$this->referralIdField])) {
            \CLE::web()->addError("This record has already been converted to a ".$this->getTitle());
            return;
        }


        $existingId = CLE::sys()->getParentEncounterId();
        $referralPage = \CLE::sys()->getPageFromPim($this->assertSetting("referral_pim"));
        $sectionPage = $referralPage->getParentPage();
        $domainPage = $sectionPage->getParentPage();

        /** @var RecordManager */
        $dm = CLE::sys()->getDataManager();
        $domain = $dm->domain($domainPage->getSetting("encounter"),CLE::sys()->getPatientId());
        if(!$domain->exists()) {
            $domain->store();
        }
        $referralSection = $dm->newSection(CLE::sys()->getPatientId(),$sectionPage->getSetting("encounter"));
        $referralSection->store();

        $this->manageEncounterCreation($referralSection, $existingId);

        $values[$this->referralIdField] = $referralSection->getId();
        CLE::web()->addMessage($this->getSetting("success_message","Successfully referred"));
    }
    abstract function manageEncounterCreation($referralSection, $sourceId);
    function copyComorbsAndMeds($sourceSection, $targetSection) {
        $dm = CLE::sys()->getDataManager();
        $sourceComorbs = $dm->child($sourceSection, self::COMORB_ENC_TYPE);
        $sourceComorbs->retrieve();
        if ($sourceComorbs->exists()) {
            $targetComorbs = $dm->newChild($targetSection, self::COMORB_ENC_TYPE);
            $targetComorbs->store($sourceComorbs->getObsValues());
            CLE::web()->addMessage("Comorbidities copied to ".$this->getTitle());
        }

        $sourceMeds = $dm->child($sourceSection, self::DRUG_ENC_TYPE);
        $sourceMeds->retrieve();

        if ($sourceMeds->exists()) {
            $targetMeds = $dm->newChild($targetSection, self::DRUG_ENC_TYPE);
            $targetMeds->store($sourceMeds->getObsValues());
            CLE::web()->addMessage("Drugs copied to ".$this->getTitle());
        }
    }
}
