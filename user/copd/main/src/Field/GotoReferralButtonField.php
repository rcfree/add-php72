 *
 * @author rcf8
 */
class GotoReferralButtonField extends \ADD_Field_Button {
    private $referralId = null;
    private $referralIdField = null;
    function createMarkup($page)
    {
        if (!$this->referralId) {
            return;
        }
        return parent::createMarkup($page); // TODO: Change the autogenerated stub
    }

    function finaliseField($page)
    {
        parent::finaliseField($page); // TODO: Change the autogenerated stub
        $this->referralIdField = $this->assertSetting("referral_id_field");
        $this->setSetting("parent_key","buttons");
    }
    function afterPopulateFields($page)
    {
        $data = $page->getData();
        if(!empty($data[$this->referralIdField])) {
            $this->referralId = $data[$this->referralIdField];
            $this->setHidden(false,$page);
        }

    }

    function getLinkTitle($page) {
        if (!$this->referralId) {
            return null;
        }
        return "<i class='fa fa-motorcycle'></i>&nbsp;Goto ".$this->getTitle();
    }
    function getLinkPath($page)
    {
        if (!$this->referralId) {
            return null;
        }
        return CLE::sys()->getPageFromPim($this->assertSetting("referral_pim"))->createMenuUri(array("eid"=>$this->referralId));
    }
}
