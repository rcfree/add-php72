class ConvertToPRButtonField extends ConvertToReferralButtonField {
    function createMarkup($page)
    {
        if (CLE::sys()->config("disable_copd_pr_link")) {
            return null;
        }
        return parent::createMarkup($page); // TODO: Change the autogenerated stub
    }
    function manageEncounterCreation($referralSection, $sourceId)
    {
        $dm = CLE::sys()->getDataManager();

        $locale = \CLE::svc(CoreServices::LOCALE);

        $copdSection = $dm->sectionById($sourceId);
        $copdSection->retrieve();

        $this->copyComorbsAndMeds($copdSection, $referralSection);

        $referral = $dm->newChild($referralSection, "pr-prog-referral");
        $sourceDischarge = $dm->child($copdSection, "copd-visit-discharge");
        $sourceDischarge->retrieve();

        $referral->setObsValues(array(
            $this->targetIdField => $sourceId,
            "referred_by" => "10",
            "referral_pway" => "2",
            "referral_date" => $locale->date("d/m/Y"),
            "main_diagnosis"=>"5",
            "consultant"=>$sourceDischarge->getObsValue("discharged_under_care_of"),
            "occupation_type"=>$sourceDischarge->getObsValue("employment_status")
        ));
        if ($sourceDischarge->exists()) {
            $referral->setObsValue("consultant", $sourceDischarge->getObsValue("discharged_under_care_of"));

        }
        $referral->store();
    }
}
